%Inputs: 
%    iq, id, desired
%    sth, cth measured
%    IMPORTANT NOTE:    
%        Fixed point range of iq and id is not full. If we use 2^12, the
%        true range will be (sqrt(3)/2)*2^12, or +/-3547
%       
%   Outputs:
%       ialpha,ibeta in whichever scale iq and id were passed
%       
%   
function [ialpha,ibeta] = inverse_park_fixed(iq,id,sth,cth)
    assert(isa(iq,'int32') & isa(id,'int32') & isa(sth,'int32') & isa(cth,'int32'),'Error: input must be type int32');
    %NOTE: If desired, it is possible to 
    % maintain a higher resolution of iq and id, if they are generated by
    % the controller to have a higher res. This function removes the 2^12
    % term from sin and cos, but not the 2^n term from iq and id
    ialpha = bitshift((id*cth - iq*sth), -12);
    ibeta = bitshift((id*sth + iq*cth), -12);
end